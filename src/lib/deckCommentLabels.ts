/** Sostituisce {chiave} con il valore (senza i `$` speciali di `replace`). */
export function fillComment(text: string, values: Record<string, string | number>): string {
  return text.replace(/\{(\w+)\}/g, (m, k: string) => (k in values ? String(values[k]) : m));
}
