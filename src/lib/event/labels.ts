/**
 * Testi degli eventi della community (10/11/2026). L'Attrix Showmatch del 16/11/2026 è un evento dei creator italiani:
 * pagina, regia, pannello dei mod e overlay sono in italiano (la pagina esiste solo in /it, vedi la pagina). Un evento
 * in un'altra lingua avrà i suoi testi accanto a questi. Segnaposto fra graffe: `fillEvent`.
 */

export function fillEvent(text: string, vars: Record<string, string | number>): string {
  return text.replace(/\{(\w+)\}/g, (m, k: string) => (k in vars ? String(vars[k]) : m));
}

/** "A", "A e B", "A, B e C" (i canali di un passaggio con più canali insieme). */
export function joinNames(names: readonly string[]): string {
  if (names.length <= 1) return names[0] ?? "";
  return `${names.slice(0, -1).join(", ")} e ${names[names.length - 1]}`;
}

/** Durata da leggere: "2 ore", "1 ora e 30 minuti", "7 minuti e 30 secondi". */
export function formatDuration(minutes: number): string {
  const sec = Math.round(Math.max(0, minutes) * 60);
  const h = Math.floor(sec / 3600);
  const m = Math.floor((sec % 3600) / 60);
  const s = sec % 60;
  const parts: string[] = [];
  if (h) parts.push(h === 1 ? "1 ora" : `${h} ore`);
  if (m) parts.push(m === 1 ? "1 minuto" : `${m} minuti`);
  if (s) parts.push(s === 1 ? "1 secondo" : `${s} secondi`);
  return parts.length ? joinNames(parts) : "0 minuti";
}

